
#include <iostream>
using namespace std;

int main() {
    int a = 10;
    int b = 3;

    cout << "a = " << a << endl;
    cout << "b = " << b << endl;

    cout << "\n--- Arithmetic Operations ---" << endl;
    cout << "Addition: " << a + b << endl;
    cout << "Subtraction: " << a - b << endl;



    double x = 10.0;
    double y = 3.0;

    cout << "Floating-point Division: " << x / y << endl;

    return 0;
}
