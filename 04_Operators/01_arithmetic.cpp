
#include <iostream>
using namespace std;

int main() { // start of main function 
    int a = 10;
    int b = 3; // variable initialization 

    cout << "a = " << a << endl;
    cout << "b = " << b << endl;

    cout << "\n--- Arithmetic Operations ---" << endl;
    cout << "Addition: " << a + b << endl;
    cout << "Subtraction: " << a - b << endl; // all operators
    cout << "Multiplication: " << a * b << endl;
    cout << "Division: " << a / b << endl;



    double x = 10.0; // variable initialization
    double y = 3.0;

    cout << "Floating-point Division: " << x / y << endl; // floating point division

    return 0;
} // end of main function 
