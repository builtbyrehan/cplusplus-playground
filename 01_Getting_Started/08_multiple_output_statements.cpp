#include <iostream>

/*
    Topic: Multiple Output Statements in C++

    In C++, std::cout is used to display output on the screen.

    We can use multiple std::cout statements to print different
    pieces of information one after another.

    Each statement normally ends with a semicolon (;).

    std::endl can be used to move the cursor to the next line.
*/

int main() {

    std::cout << "Welcome to C++ Mastery!" << std::endl;
    std::cout << "This program demonstrates multiple output statements." << std::endl;
    std::cout << "Each line is printed using a separate std::cout statement." << std::endl;
    std::cout << "Learning C++ step by step." << std::endl;

    return 0;
}