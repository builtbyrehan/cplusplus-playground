#include <iostream>
#include <limits>

int main() {

    // --------------------------------
    // 1. Signed integer
    // --------------------------------

    int signedNumber = -100;

    std::cout << "Signed number: "
              << signedNumber << '\n';


    // --------------------------------
    // 2. Unsigned integer
    // --------------------------------

    unsigned int unsignedNumber = 100;

    std::cout << "Unsigned number: "
              << unsignedNumber << '\n';




    return 0;
}
